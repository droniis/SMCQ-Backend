-- ============================================================
-- SMCQ — ESQUEMA DO BANCO DE DADOS (PostgreSQL 18, sem PostGIS)
-- Idempotente: pode ser executado várias vezes (npm run db:init)
-- sem apagar dados. Distâncias continuam calculadas por Haversine
-- na aplicação (RNF17).
--
-- Modelo alinhado ao diagrama de classes do TCC:
--   usuario ─┬─< alerta ─┬── localizacao          (1:1)
--            │           ├── fator_risco          (1:1, dados de entrada do cálculo)
--            │           ├── classificacao_risco  (1:1, resultado do IRS)
--            │           │       └─< contribuicao_criterio (1 por critério)
--            │           ├─< historico_status
--            │           ├─< observacao
--            │           ├─< arquivo_anexo
--            │           └─< solicitacao_exclusao
-- ============================================================

-- ------------------------------------------------------------
-- Usuário (senha com hash bcrypt, RNF03)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuario (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR(120) NOT NULL,
  email       VARCHAR(160) NOT NULL UNIQUE,
  senha_hash  VARCHAR(100) NOT NULL,
  perfil      VARCHAR(20)  NOT NULL CHECK (perfil IN ('ADMINISTRADOR', 'GESTOR', 'OPERADOR')),
  ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
  criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Alerta: dados da ocorrência, status e exclusão lógica
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS alerta (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo         VARCHAR(200) NOT NULL,
  descricao      TEXT         NOT NULL DEFAULT '',
  status         VARCHAR(20)  NOT NULL DEFAULT 'NOVO'
                 CHECK (status IN ('NOVO', 'EM_ANALISE', 'EM_ATENDIMENTO', 'RESOLVIDO')),
  criado_por     INTEGER      NOT NULL REFERENCES usuario (id),
  criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  excluido       BOOLEAN      NOT NULL DEFAULT FALSE,
  excluido_em    TIMESTAMPTZ,
  excluido_por   INTEGER      REFERENCES usuario (id)
);

-- Tipo de ocorrência (Etapa H). Migração idempotente: em banco que já tem
-- alertas, o DEFAULT preenche os existentes com QUEIMADA_VEGETACAO; se a
-- coluna já existe, o comando inteiro (inclusive o CHECK) é ignorado.
ALTER TABLE alerta ADD COLUMN IF NOT EXISTS tipo_ocorrencia VARCHAR(20) NOT NULL
  DEFAULT 'QUEIMADA_VEGETACAO'
  CHECK (tipo_ocorrencia IN ('QUEIMADA_VEGETACAO', 'INCENDIO_URBANO'));

-- ------------------------------------------------------------
-- Localização do alerta (1:1)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS localizacao (
  alerta_id   INTEGER PRIMARY KEY REFERENCES alerta (id) ON DELETE CASCADE,
  latitude    DOUBLE PRECISION NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
  longitude   DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  estado      VARCHAR(60)  NOT NULL DEFAULT '',
  municipio   VARCHAR(120) NOT NULL DEFAULT '',
  cep         VARCHAR(10)  NOT NULL DEFAULT '',
  logradouro  VARCHAR(200) NOT NULL DEFAULT '',
  numero      VARCHAR(20)  NOT NULL DEFAULT '',
  bairro      VARCHAR(120) NOT NULL DEFAULT ''
);

-- ------------------------------------------------------------
-- Fator de risco: dados de ENTRADA do cálculo (1:1 com o alerta)
-- Os informados pelo operador e os obtidos dos geodados.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS fator_risco (
  alerta_id           INTEGER PRIMARY KEY REFERENCES alerta (id) ON DELETE CASCADE,
  area_afetada        VARCHAR(10)      NOT NULL,                -- PEQUENA | MEDIA | GRANDE
  vento               VARCHAR(10)      NOT NULL,                -- BAIXO | MODERADO | ALTO
  direcao_vento       DOUBLE PRECISION NOT NULL DEFAULT 45,     -- graus
  pessoas_risco       BOOLEAN          NOT NULL DEFAULT FALSE,
  zona_urbana         BOOLEAN          NOT NULL DEFAULT FALSE,  -- efetiva: derivada de alerta.tipo_ocorrencia
  da_dt               DOUBLE PRECISION NOT NULL DEFAULT 0,      -- taxa de crescimento da área
  bioma               VARCHAR(30),
  bioma_origem        VARCHAR(10) CHECK (bioma_origem IN ('detectado', 'informado')),
  tipo_area           VARCHAR(30),
  tipo_area_origem    VARCHAR(10) CHECK (tipo_area_origem IN ('detectado', 'informado')),
  area_critica_fauna  VARCHAR(20),
  proxima_uc          BOOLEAN,
  geodados            JSONB                                     -- saída do geodadosService (fontes e obtidoEm)
);

-- ------------------------------------------------------------
-- Classificação de risco: RESULTADO do IRS (1:1 com o alerta)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS classificacao_risco (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alerta_id         INTEGER NOT NULL UNIQUE REFERENCES alerta (id) ON DELETE CASCADE,
  versao_algoritmo  VARCHAR(10)      NOT NULL,                  -- 'IRS v1' | 'IRS v2'
  irs               DOUBLE PRECISION NOT NULL,
  sigmoide          DOUBLE PRECISION NOT NULL,
  nivel             VARCHAR(10)      NOT NULL CHECK (nivel IN ('BAIXO', 'MODERADO', 'ALTO', 'CRITICO')),
  calculado_em      TIMESTAMPTZ      NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Contribuição de cada critério no IRS (9 linhas no v2)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contribuicao_criterio (
  classificacao_id  INTEGER NOT NULL REFERENCES classificacao_risco (id) ON DELETE CASCADE,
  criterio          VARCHAR(20)      NOT NULL,                  -- area, urbano, vento, ..., relevancia
  fator             DOUBLE PRECISION NOT NULL,
  peso              DOUBLE PRECISION NOT NULL,
  contribuicao      DOUBLE PRECISION NOT NULL,
  detalhe           JSONB            NOT NULL,                  -- objeto completo do critério (valorBruto, fonte...)
  PRIMARY KEY (classificacao_id, criterio)
);

-- ------------------------------------------------------------
-- Histórico de alterações (status e exclusão lógica)
-- JSONB preserva o tipo original dos valores ("NOVO", false).
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS historico_status (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alerta_id       INTEGER     NOT NULL REFERENCES alerta (id) ON DELETE CASCADE,
  campo           VARCHAR(20) NOT NULL,                         -- 'status' | 'excluido'
  valor_anterior  JSONB,
  valor_novo      JSONB,
  alterado_por    INTEGER     NOT NULL REFERENCES usuario (id),
  alterado_em     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Observações do alerta
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS observacao (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alerta_id   INTEGER     NOT NULL REFERENCES alerta (id) ON DELETE CASCADE,
  texto       TEXT,
  criado_por  INTEGER     NOT NULL REFERENCES usuario (id),
  criado_em   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Arquivos anexos (estrutura prevista no diagrama; ainda sem rota na API)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS arquivo_anexo (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alerta_id      INTEGER      NOT NULL REFERENCES alerta (id) ON DELETE CASCADE,
  nome_original  VARCHAR(255) NOT NULL,
  caminho        VARCHAR(500) NOT NULL,
  tipo_mime      VARCHAR(100) NOT NULL,
  tamanho_bytes  BIGINT       NOT NULL CHECK (tamanho_bytes >= 0),
  enviado_por    INTEGER      NOT NULL REFERENCES usuario (id),
  enviado_em     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Solicitações de exclusão (fluxo de aprovação)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS solicitacao_exclusao (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alerta_id       INTEGER     NOT NULL REFERENCES alerta (id) ON DELETE CASCADE,
  solicitado_por  INTEGER     NOT NULL REFERENCES usuario (id),
  motivo          TEXT        NOT NULL,
  status          VARCHAR(10) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'APROVADA', 'REJEITADA')),
  resposta        TEXT        NOT NULL DEFAULT '',
  criado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolvido_em    TIMESTAMPTZ,
  resolvido_por   INTEGER     REFERENCES usuario (id)
);

-- ------------------------------------------------------------
-- Índices (RNF20: filtros por data, status, nível de risco e região)
-- ------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_alerta_criado_em  ON alerta (criado_em DESC) WHERE NOT excluido;
CREATE INDEX IF NOT EXISTS idx_alerta_status     ON alerta (status)         WHERE NOT excluido;
CREATE INDEX IF NOT EXISTS idx_alerta_tipo_ocorr ON alerta (tipo_ocorrencia) WHERE NOT excluido;
CREATE INDEX IF NOT EXISTS idx_classif_nivel     ON classificacao_risco (nivel);
CREATE INDEX IF NOT EXISTS idx_local_regiao      ON localizacao (estado, municipio);
CREATE INDEX IF NOT EXISTS idx_local_coordenadas ON localizacao (latitude, longitude);   -- recorte por caixa antes do Haversine
CREATE INDEX IF NOT EXISTS idx_historico_alerta  ON historico_status (alerta_id, alterado_em);
CREATE INDEX IF NOT EXISTS idx_observacao_alerta ON observacao (alerta_id, criado_em);
CREATE INDEX IF NOT EXISTS idx_anexo_alerta      ON arquivo_anexo (alerta_id);
CREATE INDEX IF NOT EXISTS idx_solic_status      ON solicitacao_exclusao (status, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_solic_solicitante ON solicitacao_exclusao (solicitado_por);

-- Regra de negócio garantida pelo banco: no máximo uma solicitação PENDENTE por alerta
CREATE UNIQUE INDEX IF NOT EXISTS uq_solic_pendente ON solicitacao_exclusao (alerta_id) WHERE status = 'PENDENTE';
